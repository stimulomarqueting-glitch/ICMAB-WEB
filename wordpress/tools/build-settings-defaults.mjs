/**
 * Writes wordpress/matsurfer/inc/data/settings-defaults.php (header/footer
 * copy, default SEO texts, closing band of the news pages) from the Astro
 * content export. These are the values "Ajustes de la web" shows as the
 * originals and goes back to with "Restaurar valores originales".
 *   node wordpress/tools/export-content.mjs && node wordpress/tools/build-settings-defaults.mjs
 *
 * Keys are a contract with inc/modules/settings.php and the templates:
 * never rename or remove one.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { phpExport } from './php-export.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const c = JSON.parse(readFileSync(resolve(here, 'build/content.json'), 'utf8'));

const perLang = (lang) => {
  const s = c[lang].site;
  const nav = Object.fromEntries(s.header.nav.map((n) => [n.href.replace('/', ''), n.label]));
  const [col1, col2, col3] = s.footer.columns;
  /* the news pages close with the home page's final call to action */
  const finalCta = c[lang].home.finalCta;
  return {
    header_cta: s.header.cta,
    nav_product: nav.product,
    nav_applications: nav.applications,
    nav_research: nav.research,
    nav_team: nav.team,
    nav_contact: nav.contact,
    nav_news: lang === 'es' ? 'Noticias' : 'News',
    footer_description: s.footer.description,
    footer_cta: s.footer.cta,
    footer_col1_title: col1.title,
    footer_l_device: col1.links[0].label,
    footer_l_how: col1.links[1].label,
    footer_l_parameters: col1.links[2].label,
    footer_l_faq: col1.links[3].label,
    footer_col2_title: col2.title,
    footer_l_applications: col2.links[0].label,
    footer_l_research: col2.links[1].label,
    footer_l_team: col2.links[2].label,
    footer_l_contact: col2.links[3].label,
    footer_l_news: lang === 'es' ? 'Noticias' : 'News',
    footer_col3_title: col3.title,
    footer_l_privacy: col3.links[0].label,
    footer_l_legal: col3.links[1].label,
    footer_l_email: col3.links[2].label,
    footer_copyright: s.footer.copyright,
    footer_bottom: s.footer.bottomMono,
    seo_title: s.meta.title,
    seo_description: s.meta.description,
    og_alt: s.meta.ogAlt,
    blog_cta_title: finalCta.title,
    blog_cta_text: finalCta.text,
    blog_cta_button: finalCta.button,
  };
};

const data = {
  global: {
    contact_email: c.brand.contactEmail,
    patent_code: c.pendingData.patentFamilyCode,
    form_en: 0,
    form_es: 0,
  },
  en: perLang('en'),
  es: perLang('es'),
};

const out = resolve(here, '../matsurfer/inc/data/settings-defaults.php');
writeFileSync(out, `<?php\n/**\n * Default copy for Ajustes de la web — GENERATED by\n * wordpress/tools/build-settings-defaults.mjs from the original site copy.\n * Do not edit by hand: change the values in the admin screen instead.\n *\n * @package matsurfer\n */\n\ndefined( 'ABSPATH' ) || exit;\n\nreturn ${phpExport(data, 0)};\n`);
console.log('settings-defaults.php written');
