/**
 * "Ajustes de la web" — the admin screen for the texts that appear on every
 * page (header, footer), the default texts for Google, the closing band of
 * the news pages, the contact email and the patent code.
 *
 *  - top-level menu (dashicons-admin-generic), slug 'mats-settings'
 *    (filter mats_admin_settings_slug in inc/modules/admin.php), capability
 *    edit_pages, so Editors (ICMAB staff) can use it
