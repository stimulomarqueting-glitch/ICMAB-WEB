/**
 * The contact email of a save. It is stored once someone confirms it, and
 * the installer's final review relies on that ("someone checked the
 * address"):
 *  - a valid address different from the current one → stored (typing it is
 *    confirming it);
 *  - the same address → stored only when it was not yet and the box
 *    "Confirmo que esta dirección es correcta" is ticked; a save that does
 *    not touch it changes nothing;
 *  - empty or invalid → refused with a message: the form notifications
 *    always need an address, and the current one stays live.
 */
function mats_settings_take_email( array &$saved, array $old, string $key, array $field, string $scope, $raw, bool $confirm, array &$messages, array &$rejected ): void {
	$raw     = is_scalar( $raw ) ? trim( (string) $raw ) : '';
	$email   = sanitize_email( $raw );
	$current = mats_settings_effective( $old, $key, $scope );
	$stored  = isset( $old[ $scope ][ $key ] ) && is_scalar( $old[ $scope ][ $key ] ) && '' !== (string) $old[ $scope ][ $key ];

	if ( '' === $raw ) {
		$messages[] = array(
			'type'  => 'error',
			'text'  => sprintf( 'El email de contacto no puede quedar vacío: es la dirección a la que llegan los avisos del formulario. Sigue siendo %s. Si debe ser otra, escríbela y vuelve a guardar.', $current ),
			'field' => $scope . '-' . $key,
		);
		return;
	}
	if ( ! $email || ! is_email( $email ) || mb_strlen( $email ) > $field['max'] ) {
		$rejected[ $scope ][ $key ] = mats_settings_clean_text( $raw, 200 );
		$messages[]                 = array(
			'type'  => 'error',
			'text'  => sprintf( '«%s» no es un email válido, así que el email de contacto no ha cambiado (sigue siendo %s). Revísalo y vuelve a guardar.', mats_settings_clean_text( $raw, 200 ), $current ),
			'field' => $scope . '-' . $key,
		);
		return;
	}
	if ( strtolower( $email ) !== strtolower( $current ) ) {
		$saved[ $scope ][ $key ] = $email;
	} elseif ( ! $stored && $confirm ) {
		$saved[ $scope ][ $key ] = $email;
	}
}

