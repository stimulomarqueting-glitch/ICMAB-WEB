/** Notices of the last save ([ messages, rejected ]), read once. */
function mats_settings_take_notice(): array {
	$key  = 'mats_settings_notice_' . get_current_user_id();
	$data = get_transient( $key );
	if ( false !== $data ) {
		delete_transient( $key );
	}
	$data = is_array( $data ) ? $data : array();
	// phpcs:ignore WordPress.Security.NonceVerification.Recommended -- display only.
	if ( ! $data && isset( $_GET['mats-saved'] ) ) {
		$data = array(
			'messages' => array(
				array(
					'type' => 'success',
					'text' => 'Cambios guardados.',
				),
			),
		);
	}
	return array(
		'messages' => (array) ( $data['messages'] ?? array() ),
		'rejected' => (array) ( $data['rejected'] ?? array() ),
	);
}

/** "Ver la web: inglés · español" links. */
function mats_settings_view_links(): string {
	$out = array();
	foreach ( mats_langs() as $lang ) {
		$out[] = sprintf(
			'<a href="%1$s" target="_blank" rel="noopener">%2$s<span class="screen-reader-text"> (se abre en una pestaña nueva)</span></a>',
			esc_url( mats_home_url( $lang ) ),
			esc_html( 'es' === $lang ? 'en español' : 'en inglés' )
		);
	}
	return 'Ver la web ' . implode( ' · ', $out );
}

