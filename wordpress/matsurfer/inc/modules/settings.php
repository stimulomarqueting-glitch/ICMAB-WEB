/** One field row: label + help, then one input per language (or one). */
function mats_settings_render_row( string $key, array $field, array $saved, array $rejected, array $errors ): void {
	$label_id = 'mats-label-' . $key;
	$help_id  = 'mats-help-' . $key;
	$scopes   = mats_settings_scopes( $field );
	?>
	<div class="mats-set__row<?php echo 'global' === $field['scope'] ? ' mats-set__row--global' : ''; ?>">
		<div class="mats-set__label">
			<span class="mats-set__name" id="<?php echo esc_attr( $label_id ); ?>"><?php echo esc_html( (string) $field['label'] ); ?></span>
			<?php if ( '' !== $field['help'] ) : ?>
				<p class="mats-set__help" id="<?php echo esc_attr( $help_id ); ?>"><?php echo esc_html( (string) $field['help'] ); ?></p>
			<?php endif; ?>
		</div>
		<?php
		foreach ( $scopes as $scope ) {
			mats_settings_render_input( $key, $field, $scope, $saved, $rejected, $errors, $label_id, '' !== $field['help'] ? $help_id : '' );
		}
		?>
	</div>
	<?php
}

/** One input (with its language tag, original text and counter). */
function mats_settings_render_input( string $key, array $field, string $scope, array $saved, array $rejected, array $errors, string $label_id, string $help_id ): void {
	$id       = 'mats-' . $scope . '-' . $key;
	$default  = mats_settings_original( $key, $scope, $saved );
	$stored   = isset( $saved[ $scope ][ $key ] ) && is_scalar( $saved[ $scope ][ $key ] ) ? (string) $saved[ $scope ][ $key ] : '';
	/* the contact email nobody has confirmed yet (see mats_settings_take_email()) */
	$unsure   = 'email' === $field['type'] && '' === $stored;
	$value    = '' !== $stored ? $stored : $default;
	$error    = $errors[ $scope . '-' . $key ] ?? '';
	if ( isset( $rejected[ $scope ][ $key ] ) ) {
		$value = (string) $rejected[ $scope ][ $key ];
	}
	$is_lang  = 'global' !== $scope;
	$lang_id  = $id . '-lang';
	$labelled = $label_id . ( $is_lang ? ' ' . $lang_id : '' );
	$desc     = trim( $help_id . ( $error ? ' ' . $id . '-error' : '' ) . ( $field['count'] ? ' ' . $id . '-count' : '' ) . ( $unsure ? ' ' . $id . '-unsure' : '' ) );
	$changed  = '' !== $default && $value !== $default;
	$is_area  = in_array( $field['type'], array( 'textarea', 'long' ), true );
	/* rows for browsers that cannot size the box to its text (about 48 characters per line) */
	$rows     = max( 'long' === $field['type'] ? 1 : 3, (int) ceil( mb_strlen( '' !== $value ? $value : $default ) / 48 ) );
	$attrs    = sprintf(
		' id="%1$s" name="mats[%2$s][%3$s]" maxlength="%4$d" placeholder="%5$s" data-default="%5$s" aria-labelledby="%6$s"%7$s%8$s%9$s',
		esc_attr( $id ),
		esc_attr( $scope ),
		esc_attr( $key ),
		(int) $field['max'],
		esc_attr( $default ),
		esc_attr( $labelled ),
		$desc ? ' aria-describedby="' . esc_attr( $desc ) . '"' : '',
		$is_lang ? ' lang="' . esc_attr( mats_lang_meta( $scope )['html'] ) . '"' : '',
		$error ? ' aria-invalid="true"' : ''
	);
	?>
	<div class="mats-set__field<?php echo $error ? ' has-error' : ''; ?>" data-scope="<?php echo esc_attr( $scope ); ?>">
		<div class="mats-set__control<?php echo $is_area ? ' mats-set__control--area' : ''; ?>">
			<?php if ( $is_lang ) : ?>
				<span class="mats-set__tag" id="<?php echo esc_attr( $lang_id ); ?>" title="<?php echo esc_attr( 'es' === $scope ? 'Español' : 'Inglés' ); ?>"><span aria-hidden="true"><?php echo esc_html( strtoupper( $scope ) ); ?></span><span class="screen-reader-text"><?php echo esc_html( 'es' === $scope ? 'en español' : 'en inglés' ); ?></span></span>
			<?php endif; ?>
			<?php if ( $is_area ) : ?>
				<textarea rows="<?php echo (int) $rows; ?>"<?php echo 'long' === $field['type'] ? ' data-single="1"' : ''; ?><?php echo $attrs; // phpcs:ignore WordPress.Security.EscapeOutput -- escaped above. ?>><?php echo esc_textarea( $value ); ?></textarea>
			<?php else : ?>
				<input type="<?php echo 'email' === $field['type'] ? 'email' : 'text'; ?>" class="regular-text" value="<?php echo esc_attr( $value ); ?>"<?php echo $attrs; // phpcs:ignore WordPress.Security.EscapeOutput -- escaped above. ?><?php echo 'email' === $field['type'] ? ' autocomplete="email" spellcheck="false"' : ''; ?>>
			<?php endif; ?>
		</div>
		<?php if ( $error ) : ?>
			<p class="mats-set__error" id="<?php echo esc_attr( $id . '-error' ); ?>"><?php echo esc_html( $error ); ?></p>
		<?php endif; ?>
		<?php if ( $field['count'] ) : ?>
			<p class="mats-set__count" id="<?php echo esc_attr( $id . '-count' ); ?>" data-ideal="<?php echo (int) $field['count']; ?>" aria-live="polite"><?php echo esc_html( sprintf( '%1$d caracteres · Google muestra unos %2$d', mb_strlen( $value ), (int) $field['count'] ) ); ?></p>
		<?php endif; ?>
		<?php if ( $unsure ) : ?>
			<div class="mats-set__confirm">
				<p class="mats-set__confirmnote" id="<?php echo esc_attr( $id . '-unsure' ); ?>"><span class="dashicons dashicons-warning" aria-hidden="true"></span>Nadie ha confirmado todavía que esta dirección recibe los mensajes y que alguien los lee. Si es la buena, marca la casilla y guarda; si no, escribe la correcta.</p>
				<label class="mats-set__confirmlabel"><input type="checkbox" name="mats_email_confirm" value="1"> Confirmo que esta dirección es correcta y que alguien lee los mensajes que llegan</label>
			</div>
		<?php endif; ?>
		<?php if ( '' !== $default ) : ?>
			<p class="mats-set__orig"<?php echo $changed ? '' : ' hidden'; ?>>
				<span class="mats-set__origlabel">Original:</span> <span class="mats-set__origtext"><?php echo esc_html( $default ); ?></span>
				<button type="button" class="button-link mats-set__back hide-if-no-js" data-for="<?php echo esc_attr( $id ); ?>">Volver al original</button>
			</p>
		<?php endif; ?>
	</div>
	<?php
}

