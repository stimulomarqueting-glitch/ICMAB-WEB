/** key => [ field + section + scope ] for every editable field. */
function mats_settings_fields(): array {
	$out = array();
	foreach ( mats_settings_schema() as $section_key => $section ) {
		foreach ( (array) ( $section['groups'] ?? array() ) as $group ) {
			foreach ( (array) ( $group['fields'] ?? array() ) as $key => $field ) {
				$out[ $key ] = array_merge(
					array(
						'type'    => 'text',
						'max'     => 200,
						'help'    => '',
						'count'   => 0,
						'restore' => true,
					),
					(array) $field,
					array(
						'section' => $section_key,
						'scope'   => ( 'global' === ( $section['scope'] ?? 'lang' ) ) ? 'global' : 'lang',
					)
				);
			}
		}
	}
	return $out;
}

/** The scopes a field is stored in: [ 'en', 'es' ] or [ 'global' ]. */
function mats_settings_scopes( array $field ): array {
	return 'global' === $field['scope'] ? array( 'global' ) : mats_langs();
}

/** The saved option, normalised to [ 'global' => [], 'en' => [], 'es' => [] ]. */
function mats_settings_saved(): array {
	$saved = get_option( 'mats_settings', array() );
	$saved = is_array( $saved ) ? $saved : array();
	foreach ( array_merge( array( 'global' ), mats_langs() ) as $scope ) {
		if ( ! isset( $saved[ $scope ] ) || ! is_array( $saved[ $scope ] ) ) {
			$saved[ $scope ] = array();
		}
	}
	return $saved;
}

/** Original (default) value of a field in a scope, as generated (settings-defaults.php). */
function mats_settings_default( string $key, string $scope ): string {
	$defaults = mats_settings_defaults();
	return (string) ( $defaults[ $scope ][ $key ] ?? '' );
}

/**
 * Original value of a field as the site uses it, given a saved option
 * array (default: the stored one). The original footer line carries the
 * patent code, so once the code is changed the original line is shown
 * with the current code — after "Restaurar valores originales" of the
 * footer, too.
 */
function mats_settings_original( string $key, string $scope, ?array $saved = null ): string {
	$original = mats_settings_default( $key, $scope );
	if ( 'footer_bottom' === $key && '' !== $original ) {
		$code   = mats_settings_default( 'patent_code', 'global' );
		$patent = mats_settings_effective( $saved ?? mats_settings_saved(), 'patent_code', 'global' );
		if ( '' !== $code && $patent !== $code ) {
			$original = str_replace( $code, $patent, $original );
		}
	}
	return $original;
}

/** Value used by the site for a field, given a saved option array. */
function mats_settings_effective( array $saved, string $key, string $scope ): string {
	$value = isset( $saved[ $scope ][ $key ] ) && is_scalar( $saved[ $scope ][ $key ] ) ? (string) $saved[ $scope ][ $key ] : '';
	return '' !== $value ? $value : mats_settings_original( $key, $scope, $saved );
}

/**
 * The footer's last line as the site shows it (template-parts/site-footer.php):
 * the saved text, or the original one with the current patent code.
 */
function mats_settings_footer_line( string $lang = '' ): string {
	$lang = in_array( $lang, mats_langs(), true ) ? $lang : mats_lang();
	return trim( mats_settings_effective( mats_settings_saved(), 'footer_bottom', $lang ) );
}

/**
 * Plain text, one line, capped at $max characters.
 *
 * HTML tags, comments and <script>/<style> blocks are removed. A "<" that
 * does not open a tag ("films <50 nm", "T<300 K") is ordinary text and is
 * kept, and so is "%" followed by two letters or digits ("100%eficaz"):
 * sanitize_text_field() would silently cut or change those. Every output
 * of these values is escaped. Line breaks, tabs and repeated spaces become
 * one space. $notes receives what was changed: 'html' (tags removed) and
 * 'cut' (longer than $max).
 */
function mats_settings_clean_text( $value, int $max, ?array &$notes = null ): string {
	$notes = array();
	$value = is_scalar( $value ) ? (string) $value : '';
	$value = wp_check_invalid_utf8( $value, true );
	$flat  = static fn( string $text ): string => trim( (string) preg_replace( '/[\s\x00-\x1F\x7F]+/u', ' ', $text ) );

	$plain = (string) preg_replace( '@<(script|style)\b[^>]*>.*?</\1\s*>@is', '', $value );
	$plain = (string) preg_replace( '@<!--.*?(?:-->|$)@s', '', $plain );
	$plain = (string) preg_replace( '@<(?:br|p|div|li|tr|td|th|h[1-6])\b[^<>]*>@i', ' ', $plain );
	$plain = (string) preg_replace( '@<(?:/?[a-zA-Z][a-zA-Z0-9-]*\b[^<>]*|![^<>]*|\?[^<>]*)>@', '', $plain );
	if ( $flat( $plain ) !== $flat( $value ) ) {
		$notes[] = 'html';
	}
	$value = $flat( $plain );

	if ( $max > 0 && mb_strlen( $value ) > $max ) {
		$value   = trim( mb_substr( $value, 0, $max ) );
		$notes[] = 'cut';
	}
	return $value;
}

/**
 * Stores a value following the "only what differs" rule: empty or equal to
 * the original → removed (the site uses the original).
 */
function mats_settings_put( array &$saved, string $key, string $scope, string $value ): void {
	if ( '' === $value || mats_settings_default( $key, $scope ) === $value || mats_settings_original( $key, $scope, $saved ) === $value ) {
		unset( $saved[ $scope ][ $key ] );
		return;
	}
	$saved[ $scope ][ $key ] = $value;
}

/** "«Descripción» (Pie de página, en inglés)" — names a field in the notices. */
function mats_settings_field_name( array $field, string $scope ): string {
	$schema  = mats_settings_schema();
	$section = (string) ( $schema[ $field['section'] ]['title'] ?? '' );
	$where   = array_filter( array( $section, 'global' === $scope ? '' : ( 'es' === $scope ? 'en español' : 'en inglés' ) ) );
	return sprintf( '«%s»%s', (string) $field['label'], $where ? ' (' . implode( ', ', $where ) . ')' : '' );
}

