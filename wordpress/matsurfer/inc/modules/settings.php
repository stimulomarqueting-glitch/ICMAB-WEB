/** Small behaviour layer (no dependencies): originals, counters, confirmations, unsaved changes. */
function mats_settings_inline_js(): string {
	return <<<'JS'
(function () {
  'use strict';
  var form = document.getElementById('mats-settings-form');
  if (!form) return;
  var dirty = false;
  var dirtyNote = form.querySelector('.mats-set__dirty');

  function fieldOf(input) {
    return input.closest ? input.closest('.mats-set__field') : null;
  }
  function syncOriginal(input) {
    var box = fieldOf(input);
    var orig = box && box.querySelector('.mats-set__orig');
    if (!orig) return;
    var value = input.value.trim();
    orig.hidden = value === '' || value === (input.getAttribute('data-default') || '');
  }
  function syncCount(input) {
    var box = fieldOf(input);
    var count = box && box.querySelector('.mats-set__count');
    if (!count) return;
    var ideal = parseInt(count.getAttribute('data-ideal'), 10) || 0;
    var length = (input.value || input.getAttribute('placeholder') || '').length;
    count.textContent = length + ' caracteres · Google muestra unos ' + ideal;
    count.classList.toggle('is-over', ideal > 0 && length > ideal);
  }
  function setDirty(on) {
    dirty = on;
    if (dirtyNote) dirtyNote.hidden = !on;
  }

  var autosize = !(window.CSS && CSS.supports && CSS.supports('field-sizing', 'content'));
  function grow(area) {
    if (!autosize || area.tagName !== 'TEXTAREA') return;
    area.style.height = 'auto';
    area.style.height = area.scrollHeight + 2 + 'px';
  }

  Array.prototype.forEach.call(form.querySelectorAll('input[data-default], textarea[data-default]'), function (input) {
    syncCount(input);
    grow(input);
  });

  /* one-line texts shown in a growing box: Enter adds no line break */
  form.addEventListener('keydown', function (e) {
    var t = e.target;
    if (e.key === 'Enter' && t && t.getAttribute && t.getAttribute('data-single') === '1') e.preventDefault();
  });

  form.addEventListener('input', function (e) {
    var t = e.target;
    if (!t || !t.hasAttribute || !t.hasAttribute('data-default')) return;
    setDirty(true);
    syncOriginal(t);
    syncCount(t);
    grow(t);
    if (t.getAttribute('aria-invalid') === 'true') {
      t.removeAttribute('aria-invalid');
      var box = fieldOf(t);
      if (box) box.classList.remove('has-error');
    }
  });

  form.addEventListener('click', function (e) {
    var t = e.target;
    if (!t || !t.closest) return;
    var back = t.closest('.mats-set__back');
    if (back) {
      e.preventDefault();
      var input = document.getElementById(back.getAttribute('data-for'));
      if (!input) return;
      input.value = input.getAttribute('data-default') || '';
      input.dispatchEvent(new Event('input', { bubbles: true }));
      input.focus();
      return;
    }
    var restore = t.closest('.mats-set__restore');
    if (restore && !window.confirm(restore.getAttribute('data-confirm') || '')) {
      e.preventDefault();
    }
  });

  /* the contact email's "Confirmo…" box */
  form.addEventListener('change', function (e) {
    if (e.target && e.target.name === 'mats_email_confirm') setDirty(true);
  });

  form.addEventListener('submit', function () {
    setDirty(false);
  });

  window.addEventListener('beforeunload', function (e) {
    if (!dirty) return;
    e.preventDefault();
    e.returnValue = '';
  });

  /* an email error: bring the field into view */
  var invalid = form.querySelector('[aria-invalid="true"]');
  if (invalid) {
    invalid.scrollIntoView({ block: 'center' });
    invalid.focus();
  }
})();
JS;
}
