 *    new code on save
 *
 * Storage and reading: inc/settings-api.php (option mats_settings,
 * mats_setting()). Originals: inc/data/settings-defaults.php, generated by
 * wordpress/tools/build-settings-defaults.mjs. Styles:
 * assets/css/settings-admin.css; the small behaviour script is inline.
 *
