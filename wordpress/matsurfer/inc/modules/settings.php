 * was not changed by hand needs nothing (its original is shown with the
 * current code, see mats_settings_original()); a line changed by hand gets
 * the old code — or the very first one — replaced by the new one.
 *
 * @return array Messages for the screen.
 */
function mats_settings_sync_patent( array &$saved, array $old ): array {
	$old_patent = mats_settings_effective( $old, 'patent_code', 'global' );
	$new_patent = mats_settings_effective( $saved, 'patent_code', 'global' );
	$first      = mats_settings_default( 'patent_code', 'global' );
	if ( '' === $new_patent || $old_patent === $new_patent ) {
		return array();
	}
	$synced  = array();
	$missing = array();
	foreach ( mats_langs() as $lang ) {
		$name   = 'es' === $lang ? 'en español' : 'en inglés';
		$stored = isset( $saved[ $lang ]['footer_bottom'] ) && is_scalar( $saved[ $lang ]['footer_bottom'] ) ? (string) $saved[ $lang ]['footer_bottom'] : '';
		if ( '' === $stored ) {
			if ( '' !== $first && false !== strpos( mats_settings_default( 'footer_bottom', $lang ), $first ) ) {
				$synced[] = $name;
			}
			continue;
		}
		if ( false !== strpos( $stored, $new_patent ) ) {
			continue; // already written with the new code
		}
		$line = '' !== $old_patent ? str_replace( $old_patent, $new_patent, $stored ) : $stored;
		if ( '' !== $first && $first !== $new_patent ) {
			$line = str_replace( $first, $new_patent, $line );
		}
		if ( $line !== $stored ) {
			$saved[ $lang ]['footer_bottom'] = $line;
			$synced[]                        = $name;
		} elseif ( false === strpos( $line, $new_patent ) ) {
			$missing[] = $name;
		}
	}
	$messages = array();
	if ( $synced ) {
		$messages[] = array(
			'type' => 'info',
			'text' => sprintf( 'El código de la patente también se ha cambiado en la línea final del pie de página, %1$s (ahora: %2$s).', implode( ' y ', $synced ), $new_patent ),
		);
	}
	if ( $missing ) {
		$messages[] = array(
			'type' => 'warning',
			'text' => sprintf( 'La línea final del pie de página %1$s no lleva el código de la patente anterior, así que no se ha tocado. Si debe llevar el nuevo (%2$s), escríbelo en «Texto pequeño de la derecha».', implode( ' y ', $missing ), $new_patent ),
		);
	}
	return $messages;
}

/**
 * The address that receives the contact form messages has changed: the
 * previous address and the site administrator are told who changed it, so
 * a change nobody expected (a mistake, or someone else using an Editor
 * account) is noticed at once. Plain text email through wp_mail().
 *
 * @return string[] Addresses the notice was sent to (empty if it could not be sent).
 */
function mats_settings_notify_email_change( string $before, string $after ): array {
	$to = array();
	foreach ( array( $before, (string) get_option( 'admin_email' ) ) as $address ) {
		$address = sanitize_email( $address );
		if ( $address && is_email( $address ) && ! in_array( strtolower( $address ), array_map( 'strtolower', $to ), true ) ) {
			$to[] = $address;
		}
	}
	if ( ! $to ) {
		return array();
	}
	$user = wp_get_current_user();
	$who  = $user && $user->exists() ? sprintf( '%1$s (usuario «%2$s»)', $user->display_name, $user->user_login ) : 'Alguien';
	$site = wp_specialchars_decode( (string) get_option( 'blogname' ), ENT_QUOTES );
	$site = '' !== $site ? $site : wp_parse_url( home_url(), PHP_URL_HOST );

	$subject = sprintf( '[%s] Ha cambiado el email que recibe los mensajes del formulario de contacto', $site );
	$body    = implode(
		"\n",
		array(
			'Hola:',
			'',
			sprintf( '%1$s ha cambiado el email de contacto de la web %2$s en «Ajustes de la web».', $who, home_url( '/' ) ),
			'',
			'Antes: ' . $before,
			'Ahora: ' . $after,
			'Fecha: ' . wp_date( 'j/m/Y H:i' ),
			'',
			sprintf( 'Desde ahora, los avisos del formulario de contacto llegan a %s.', $after ),
			'',
			'Si no esperabas este cambio, entra en la web y revísalo:',
			mats_settings_page_url( 'contact' ),
			'Si no puedes entrar, avisa a la persona que administra la web.',
		)
	);
	return wp_mail( $to, $subject, $body ) ? $to : array();
}

/** admin-post.php?action=mats_settings_save */
function mats_settings_handle_save(): void {
	if ( ! current_user_can( mats_settings_capability() ) ) {
		wp_die(
			esc_html( 'No tienes permiso para cambiar los ajustes de la web. Pide ayuda a la persona que administra la web.' ),
			esc_html( 'Sin permiso' ),
			array(
				'response'  => 403,
				'back_link' => true,
			)
		);
	}
	check_admin_referer( MATS_SETTINGS_ACTION, 'mats_settings_nonce' );

	// phpcs:ignore WordPress.Security.ValidatedSanitizedInput.InputNotSanitized -- every value is sanitised below, field by field.
	$posted   = isset( $_POST['mats'] ) && is_array( $_POST['mats'] ) ? wp_unslash( $_POST['mats'] ) : array();
	$restore  = isset( $_POST['mats_restore'] ) && is_scalar( $_POST['mats_restore'] ) ? sanitize_key( wp_unslash( $_POST['mats_restore'] ) ) : '';
	$confirm  = ! empty( $_POST['mats_email_confirm'] );
	$schema   = mats_settings_schema();
	$fields   = mats_settings_fields();
	$old      = mats_settings_saved();
	$saved    = $old;
	$messages = array();
	$rejected = array();
	$cleaned  = array( 'html' => array(), 'cut' => array() );

	if ( '' !== $restore && ! isset( $schema[ $restore ] ) ) {
		$restore = '';
	}

	foreach ( $fields as $key => $field ) {
		foreach ( mats_settings_scopes( $field ) as $scope ) {
			if ( ! isset( $posted[ $scope ] ) || ! is_array( $posted[ $scope ] ) || ! array_key_exists( $key, $posted[ $scope ] ) ) {
				continue; // not on the form: leave it as it is
			}
			$raw = $posted[ $scope ][ $key ];
			if ( 'email' === $field['type'] ) {
				mats_settings_take_email( $saved, $old, $key, $field, $scope, $raw, $confirm, $messages, $rejected );
				continue;
			}
			$notes = array();
			$value = mats_settings_clean_text( $raw, (int) $field['max'], $notes );
			foreach ( $notes as $note ) {
				$cleaned[ $note ][ $scope . '-' . $key ] = mats_settings_field_name( $field, $scope );
			}
			mats_settings_put( $saved, $key, $scope, $value );
		}
	}

	/* "Restaurar valores originales" of one section (fields marked 'restore' => false stay as they are) */
	$kept = array();
	if ( '' !== $restore ) {
		$reset = array();
		foreach ( $fields as $key => $field ) {
			if ( $field['section'] !== $restore ) {
				continue;
			}
			if ( ! $field['restore'] ) {
				$kept[] = '«' . $field['label'] . '»';
				continue;
			}
			foreach ( mats_settings_scopes( $field ) as $scope ) {
				unset( $saved[ $scope ][ $key ], $rejected[ $scope ][ $key ] );
				$reset[] = $scope . '-' . $key;
			}
		}
		/* errors of the fields that were just reset no longer apply */
		$messages = array_values( array_filter( $messages, static fn( $m ) => empty( $m['field'] ) || ! in_array( $m['field'], $reset, true ) ) );
		foreach ( array_keys( $cleaned ) as $note ) {
			$cleaned[ $note ] = array_diff_key( $cleaned[ $note ], array_flip( $reset ) );
		}
	}

	/* a new patent code also goes into the footer's last line */
	$messages = array_merge( $messages, mats_settings_sync_patent( $saved, $old ) );

	/* "only what differs" once more, now that the patent code is final (the original footer line depends on it) */
	foreach ( $fields as $key => $field ) {
		if ( 'email' === $field['type'] ) {
			continue; // a stored email records that someone confirmed it, even the original one
		}
		foreach ( mats_settings_scopes( $field ) as $scope ) {
			if ( isset( $saved[ $scope ][ $key ] ) && is_scalar( $saved[ $scope ][ $key ] ) ) {
				mats_settings_put( $saved, $key, $scope, (string) $saved[ $scope ][ $key ] );
			}
		}
	}

	if ( $cleaned['html'] ) {
		$messages[] = array(
			'type' => 'warning',
			'text' => sprintf( 'Aquí solo se admite texto normal, así que se ha quitado el código HTML (lo que va entre < y >) de: %s. Revisa que el texto se lee bien.', implode( ', ', $cleaned['html'] ) ),
		);
	}
	if ( $cleaned['cut'] ) {
		$messages[] = array(
			'type' => 'warning',
			'text' => sprintf( 'Estos textos eran demasiado largos y se han recortado: %s. Revisa cómo han quedado.', implode( ', ', $cleaned['cut'] ) ),
		);
	}

	$changed = $saved !== $old;
	if ( $changed ) {
		update_option( 'mats_settings', $saved, true );
		/* page caches (LiteSpeed on Hostinger…) keep the old header/footer otherwise */
		do_action( 'litespeed_purge_all' );
		do_action( 'mats_settings_saved', $saved, $old );
	}

	$old_email = mats_settings_effective( $old, 'contact_email', 'global' );
	$new_email = mats_settings_effective( $saved, 'contact_email', 'global' );
	if ( $changed && strtolower( $old_email ) !== strtolower( $new_email ) ) {
		$told       = mats_settings_notify_email_change( $old_email, $new_email );
		$messages[] = array(
			'type' => 'warning',
			'text' => sprintf( 'El email de contacto ahora es %s. Envía una prueba desde la página Contacto para comprobar que el aviso llega (mira también en la carpeta de spam).', $new_email )
				. ( $told ? sprintf( ' Se ha enviado un aviso del cambio a %s.', implode( ' y ', $told ) ) : '' ),
		);
	}

	if ( '' !== $restore ) {
		array_unshift(
			$messages,
			array(
				'type'      => 'success',
				'text'      => $kept
					? sprintf( 'Listo: «%1$s» vuelve a tener los valores originales, salvo %2$s, que no cambia. Si habías cambiado algo en otras secciones, también se ha guardado.', $schema[ $restore ]['title'], implode( ', ', $kept ) )
					: sprintf( 'Listo: «%s» vuelve a tener los textos originales. Si habías cambiado algo en otras secciones, también se ha guardado.', $schema[ $restore ]['title'] ),
				'viewlinks' => true,
			)
		);
	} elseif ( ! array_filter( $messages, static fn( $m ) => 'error' === $m['type'] ) ) {
		array_unshift(
			$messages,
			array(
				'type'      => 'success',
				'text'      => $changed ? 'Cambios guardados. Ya se ven en toda la web.' : 'No había nada nuevo que guardar.',
				'viewlinks' => $changed,
			)
		);
	} elseif ( $changed ) {
		array_unshift(
			$messages,
			array(
				'type' => 'success',
				'text' => 'El resto de cambios se han guardado.',
			)
		);
	}

	set_transient(
		'mats_settings_notice_' . get_current_user_id(),
		array(
			'messages' => $messages,
			'rejected' => $rejected,
		),
		5 * MINUTE_IN_SECONDS
	);

	$target = add_query_arg( 'mats-saved', '1', mats_settings_page_url() );
	if ( '' !== $restore ) {
		$target .= '#mats-sec-' . $restore;
	}
	wp_safe_redirect( $target );
	exit;
}

